alter table public.profiles
  add column if not exists phone text not null default ''
  check (char_length(phone) <= 32);

create table if not exists public.store_addresses (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references auth.users (id) on delete cascade,
  label text not null default 'Nhà riêng' check (char_length(btrim(label)) between 1 and 60),
  recipient_name text not null check (char_length(btrim(recipient_name)) between 2 and 120),
  phone text not null check (char_length(btrim(phone)) between 6 and 32),
  street text not null check (char_length(btrim(street)) between 3 and 240),
  district text not null check (char_length(btrim(district)) between 2 and 120),
  city text not null check (char_length(btrim(city)) between 2 and 120),
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists store_addresses_one_default_per_customer
  on public.store_addresses (customer_id) where is_default;
create index if not exists store_addresses_customer_idx
  on public.store_addresses (customer_id, created_at desc);

create table if not exists public.store_wishlists (
  customer_id uuid not null references auth.users (id) on delete cascade,
  product_id bigint not null references public.store_products (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (customer_id, product_id)
);

create table if not exists public.newsletter_subscriptions (
  id bigint generated by default as identity primary key,
  email text not null unique,
  subscribed_at timestamptz not null default now(),
  is_active boolean not null default true
);

alter table public.store_addresses enable row level security;
alter table public.store_wishlists enable row level security;
alter table public.newsletter_subscriptions enable row level security;

revoke all on public.store_addresses, public.store_wishlists,
  public.newsletter_subscriptions from anon, authenticated;
grant select on public.store_addresses, public.store_wishlists to authenticated;
grant insert, update, delete on public.store_addresses, public.store_wishlists to authenticated;
grant all on public.store_addresses, public.store_wishlists,
  public.newsletter_subscriptions to service_role;
grant usage, select on sequence public.newsletter_subscriptions_id_seq to service_role;
grant update (full_name, phone) on public.profiles to authenticated;

drop policy if exists "Customers can manage their own addresses" on public.store_addresses;
create policy "Customers can manage their own addresses"
  on public.store_addresses for all to authenticated
  using (customer_id = (select auth.uid()))
  with check (customer_id = (select auth.uid()));

drop policy if exists "Customers can manage their own wishlist" on public.store_wishlists;
create policy "Customers can manage their own wishlist"
  on public.store_wishlists for all to authenticated
  using (customer_id = (select auth.uid()))
  with check (customer_id = (select auth.uid()));

create or replace function public.save_customer_address(
  p_id uuid,
  p_label text,
  p_recipient_name text,
  p_phone text,
  p_street text,
  p_district text,
  p_city text,
  p_is_default boolean
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  customer uuid := auth.uid();
  address_id uuid;
begin
  if customer is null then
    raise exception 'Vui lòng đăng nhập để quản lý địa chỉ.';
  end if;
  if p_label is null or char_length(btrim(p_label)) not between 1 and 60
    or p_recipient_name is null or char_length(btrim(p_recipient_name)) not between 2 and 120
    or p_phone is null or char_length(btrim(p_phone)) not between 6 and 32
    or p_street is null or char_length(btrim(p_street)) not between 3 and 240
    or p_district is null or char_length(btrim(p_district)) not between 2 and 120
    or p_city is null or char_length(btrim(p_city)) not between 2 and 120 then
    raise exception 'Thông tin địa chỉ không hợp lệ.';
  end if;

  if p_id is not null then
    perform 1 from public.store_addresses
      where id = p_id and customer_id = customer for update;
    if not found then
      raise exception 'Không tìm thấy địa chỉ của tài khoản.';
    end if;
  end if;

  if p_is_default then
    update public.store_addresses
      set is_default = false, updated_at = now()
      where customer_id = customer and is_default
        and (p_id is null or id <> p_id);
  end if;

  if p_id is null then
    insert into public.store_addresses (
      customer_id, label, recipient_name, phone, street, district, city, is_default
    ) values (
      customer, btrim(p_label), btrim(p_recipient_name), btrim(p_phone),
      btrim(p_street), btrim(p_district), btrim(p_city), coalesce(p_is_default, false)
    ) returning id into address_id;
  else
    update public.store_addresses set
      label = btrim(p_label),
      recipient_name = btrim(p_recipient_name),
      phone = btrim(p_phone),
      street = btrim(p_street),
      district = btrim(p_district),
      city = btrim(p_city),
      is_default = coalesce(p_is_default, false),
      updated_at = now()
    where id = p_id and customer_id = customer
    returning id into address_id;
  end if;

  return address_id;
end;
$$;

create or replace function public.delete_customer_address(p_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  customer uuid := auth.uid();
  was_default boolean;
begin
  if customer is null then
    raise exception 'Vui lòng đăng nhập để quản lý địa chỉ.';
  end if;
  delete from public.store_addresses
    where id = p_id and customer_id = customer
    returning is_default into was_default;
  if not found then
    raise exception 'Không tìm thấy địa chỉ của tài khoản.';
  end if;
  if was_default then
    update public.store_addresses
      set is_default = true, updated_at = now()
      where id = (
        select id from public.store_addresses
        where customer_id = customer
        order by created_at desc
        limit 1
      );
  end if;
end;
$$;

create or replace function public.cancel_customer_order(p_order_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  customer uuid := auth.uid();
  current_status text;
begin
  if customer is null then
    raise exception 'Vui lòng đăng nhập để hủy đơn hàng.';
  end if;

  select status into current_status
  from public.store_orders
  where id = p_order_id and customer_id = customer
  for update;
  if current_status is null then
    raise exception 'Không tìm thấy đơn hàng của tài khoản.';
  end if;
  if current_status <> 'pending' then
    raise exception 'Chỉ có thể hủy đơn hàng đang chờ xác nhận.';
  end if;

  update public.store_products product
    set inventory = product.inventory + items.quantity, updated_at = now()
    from (
      select product_id, sum(quantity)::integer as quantity
      from public.store_order_items
      where order_id = p_order_id and product_id is not null
      group by product_id
    ) items
    where items.product_id = product.id;

  update public.store_orders
    set status = 'cancelled', updated_at = now()
    where id = p_order_id and customer_id = customer and status = 'pending';
end;
$$;

create or replace function public.sync_customer_wishlist(p_product_ids bigint[])
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  customer uuid := auth.uid();
begin
  if customer is null then
    raise exception 'Vui lòng đăng nhập để đồng bộ danh sách yêu thích.';
  end if;
  if coalesce(cardinality(p_product_ids), 0) > 500 then
    raise exception 'Danh sách yêu thích vượt quá giới hạn.';
  end if;
  if exists (
    select 1
    from unnest(coalesce(p_product_ids, '{}'::bigint[])) requested(id)
    left join public.store_products product
      on product.id = requested.id
    where product.id is null
  ) then
    raise exception 'Danh sách có sản phẩm không hợp lệ.';
  end if;

  delete from public.store_wishlists
  where customer_id = customer
    and product_id <> all(coalesce(p_product_ids, '{}'::bigint[]));

  insert into public.store_wishlists (customer_id, product_id)
  select customer, requested.id
  from unnest(coalesce(p_product_ids, '{}'::bigint[])) requested(id)
  on conflict (customer_id, product_id) do nothing;
end;
$$;

create or replace function public.subscribe_store_newsletter(p_email text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  normalized_email text := lower(btrim(p_email));
begin
  if normalized_email is null
    or char_length(normalized_email) not between 5 and 254
    or normalized_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception 'Vui lòng nhập địa chỉ email hợp lệ.';
  end if;

  insert into public.newsletter_subscriptions (email, subscribed_at, is_active)
  values (normalized_email, now(), true)
  on conflict (email) do update
    set subscribed_at = now(), is_active = true;
end;
$$;

