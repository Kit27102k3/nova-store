alter table public.store_orders
  add column if not exists ghn_order_code text,
  add column if not exists shipping_status text,
  add column if not exists shipping_status_label text,
  add column if not exists shipping_tracking_url text;

create index if not exists store_orders_ghn_order_code_idx
  on public.store_orders (ghn_order_code)
  where ghn_order_code is not null;

create table if not exists public.store_order_events (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.store_orders (id) on delete cascade,
  event_type text not null check (event_type in ('order', 'status', 'tracking', 'shipping')),
  title text not null check (char_length(title) between 1 and 160),
  description text not null default '',
  source text not null check (source in ('system', 'admin', 'ghn')),
  email_status text not null default 'pending'
    check (email_status in ('pending', 'sending', 'sent', 'failed', 'skipped')),
  email_attempts integer not null default 0 check (email_attempts >= 0),
  email_claimed_at timestamptz,
  email_sent_at timestamptz,
  email_error text,
  created_at timestamptz not null default now()
);

create index if not exists store_order_events_order_created_idx
  on public.store_order_events (order_id, created_at desc);
create index if not exists store_order_events_pending_email_idx
  on public.store_order_events (created_at)
  where email_status = 'pending';

alter table public.store_order_events enable row level security;
revoke all on public.store_order_events from anon, authenticated;
grant select on public.store_order_events to authenticated;
grant all on public.store_order_events to service_role;
grant usage, select on sequence public.store_order_events_id_seq to service_role;

drop policy if exists "Customers can read their own order events"
  on public.store_order_events;
create policy "Customers can read their own order events"
  on public.store_order_events for select to authenticated
  using (exists (
    select 1
    from public.store_orders order_row
    where order_row.id = store_order_events.order_id
      and order_row.customer_id = (select auth.uid())
  ));

create or replace function public.record_store_order_event()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  event_kind text;
  event_title text;
  event_description text := '';
  event_source text := 'system';
begin
  if tg_op = 'INSERT' then
    event_kind := 'order';
    event_title := 'Đã tiếp nhận đơn hàng';
    event_description := 'Nova Store đã nhận được đơn hàng của bạn.';
  elsif new.status is distinct from old.status then
    event_kind := 'status';
    event_source := 'admin';
    event_title := case new.status
      when 'pending' then 'Đơn hàng đang chờ xác nhận'
      when 'confirmed' then 'Đơn hàng đã được xác nhận'
      when 'shipping' then 'Đơn hàng đang được giao'
      when 'completed' then 'Đơn hàng đã hoàn thành'
      when 'cancelled' then 'Đơn hàng đã bị hủy'
      else 'Trạng thái đơn hàng đã cập nhật'
    end;
  elsif new.ghn_order_code is distinct from old.ghn_order_code then
    event_kind := 'tracking';
    event_source := 'admin';
    event_title := 'Đã cập nhật mã vận đơn GHN';
    event_description := coalesce(new.ghn_order_code, '');
  elsif new.shipping_status is distinct from old.shipping_status then
    event_kind := 'shipping';
    event_source := 'ghn';
    event_title := coalesce(new.shipping_status_label, 'Trạng thái vận chuyển đã cập nhật');
    event_description := 'Trạng thái được đồng bộ tự động từ GHN.';
  else
    return new;
  end if;

  insert into public.store_order_events (
    order_id, event_type, title, description, source
  ) values (
    new.id, event_kind, event_title, event_description, event_source
  );
  return new;
end;
$$;

drop trigger if exists store_orders_record_event on public.store_orders;
create trigger store_orders_record_event
  after insert or update of status, ghn_order_code, shipping_status
  on public.store_orders
  for each row execute function public.record_store_order_event();

insert into public.store_order_events (
  order_id, event_type, title, description, source, email_status
)
select
  order_row.id,
  'order',
  case order_row.status
    when 'pending' then 'Đơn hàng đang chờ xác nhận'
    when 'confirmed' then 'Đơn hàng đã được xác nhận'
    when 'shipping' then 'Đơn hàng đang được giao'
    when 'completed' then 'Đơn hàng đã hoàn thành'
    when 'cancelled' then 'Đơn hàng đã bị hủy'
    else 'Đã tiếp nhận đơn hàng'
  end,
  'Trạng thái hiện tại được ghi nhận khi bật lịch sử vận chuyển.',
  'system',
  'skipped'
from public.store_orders order_row
where not exists (
  select 1
  from public.store_order_events event_row
  where event_row.order_id = order_row.id
);
