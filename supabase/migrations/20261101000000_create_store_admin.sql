create table if not exists public.store_categories (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(btrim(name)) between 2 and 80),
  slug text not null unique,
  description text not null default '',
  image text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.store_products (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null check (char_length(btrim(name)) between 2 and 160),
  category_id bigint not null references public.store_categories (id) on delete restrict,
  price integer not null check (price >= 0),
  original_price integer check (original_price is null or original_price >= price),
  rating numeric(2, 1) not null default 0 check (rating between 0 and 5),
  reviews integer not null default 0 check (reviews >= 0),
  badge text check (badge is null or badge in ('Bán chạy', 'Mới')),
  is_new boolean not null default false,
  is_active boolean not null default true,
  inventory integer not null default 0 check (inventory >= 0),
  images text[] not null default '{}',
  description text not null default '',
  details text[] not null default '{}',
  variants jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.store_settings (
  id text primary key default 'store' check (id = 'store'),
  store_name text not null default 'Nova Store',
  support_email text not null default 'hello@novastore.example',
  shipping_threshold integer not null default 499000 check (shipping_threshold >= 0),
  shipping_fee integer not null default 30000 check (shipping_fee >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.store_orders (
  id bigint generated by default as identity primary key,
  order_number text unique,
  customer_id uuid references auth.users (id) on delete set null,
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  address text not null,
  district text not null,
  city text not null,
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'shipping', 'completed', 'cancelled')),
  subtotal integer not null check (subtotal >= 0),
  shipping_fee integer not null check (shipping_fee >= 0),
  total integer not null check (total = subtotal + shipping_fee),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.store_order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.store_orders (id) on delete cascade,
  product_id bigint references public.store_products (id) on delete set null,
  product_name text not null,
  product_slug text not null,
  image text not null default '',
  variant text,
  unit_price integer not null check (unit_price >= 0),
  quantity integer not null check (quantity between 1 and 99)
);

create index if not exists store_products_category_idx on public.store_products (category_id);
create index if not exists store_products_active_idx on public.store_products (is_active);
create index if not exists store_orders_created_at_idx on public.store_orders (created_at desc);
create index if not exists store_orders_email_idx on public.store_orders (customer_email);
create index if not exists store_order_items_order_idx on public.store_order_items (order_id);

