create or replace function public.admin_set_order_status(p_order_id bigint, p_status text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  old_status text;
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'Không có quyền cập nhật đơn hàng.';
  end if;
  if p_status not in ('pending', 'confirmed', 'shipping', 'completed', 'cancelled') then
    raise exception 'Trạng thái đơn hàng không hợp lệ.';
  end if;

  select status into old_status from public.store_orders where id = p_order_id for update;
  if old_status is null then
    raise exception 'Không tìm thấy đơn hàng.';
  end if;
  if old_status in ('completed', 'cancelled') and p_status <> old_status then
    raise exception 'Không thể thay đổi trạng thái cuối cùng của đơn hàng.';
  end if;

  if p_status = 'cancelled' and old_status <> 'cancelled' then
    update public.store_products product
      set inventory = product.inventory + items.quantity, updated_at = now()
      from (
        select product_id, sum(quantity)::integer as quantity
        from public.store_order_items
        where order_id = p_order_id and product_id is not null
        group by product_id
      ) items
      where items.product_id = product.id;
  end if;

  update public.store_orders
    set status = p_status, updated_at = now()
    where id = p_order_id;
end;
$$;

revoke all on function public.admin_set_order_status(bigint, text) from public, anon, authenticated;
grant execute on function public.admin_set_order_status(bigint, text) to service_role;
